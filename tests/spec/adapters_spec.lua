describe("gopkg", function()
  local gopkg = require("rtfm.adapters.gopkg")

  it("parses symbol search results", function()
    local items = gopkg.parse_search(fixture("gopkg_search_symbol.html"))
    eq(3, #items)
    eq("context.WithCancel", items[1].title)
    eq("https://pkg.go.dev/context#WithCancel", items[1].url)
    eq("WithCancel", items[1].fragment)
    contains(items[2].kind, "golang.org/x/net/context")
  end)

  it("lists packages of a versioned module", function()
    local src = gopkg.versioned("std", "go1.22.0")
    local items = gopkg.parse_directories(fixture("gopkg_std_dirs.html"), src)
    ok(#items >= 10)
    eq("archive/tar", items[1].title)
    eq("https://pkg.go.dev/archive/tar@go1.22.0", items[1].url)
  end)

  it("builds versioned urls and ids", function()
    local m = gopkg.versioned("golang.org/x/sync", "v0.10.0")
    eq("gopkg:golang.org/x/sync@v0.10.0", m.id)
    eq("https://pkg.go.dev/golang.org/x/sync@v0.10.0/errgroup", gopkg.versioned_url(m, "golang.org/x/sync/errgroup"))
    eq("go1.22.0", gopkg.std_version("1.22"))
    eq("go1.22.5", gopkg.std_version("go1.22.5"))
    eq("go1.19", gopkg.std_version("1.19"))
    eq("golang.org/x/sync@v0.10.0", gopkg.from_param("golang.org/x/sync@v0.10.0").module .. "@" .. gopkg.from_param("golang.org/x/sync@v0.10.0").version)
  end)

  it("keeps links in a versioned source at that version", function()
    local src = gopkg.versioned("std", "go1.22.0")
    local r = gopkg.resolve(src, "https://pkg.go.dev/io#Reader")
    eq("https://pkg.go.dev/io@go1.22.0#Reader", r.item.url)
    eq(nil, gopkg.resolve(src, "https://example.com/x"))
  end)
end)

describe("docsrs", function()
  local docsrs = require("rtfm.adapters.docsrs")
  it("parses all.html into items", function()
    local src = docsrs.versioned("serde", "1.0.200")
    local items = docsrs.parse_all(fixture("docsrs_serde_all.html"), src)
    ok(#items > 20)
    eq("crate", items[1].kind)
    local found
    for _, it in ipairs(items) do
      if it.title == "de::value::StrDeserializer" then
        found = it
      end
    end
    ok(found, "StrDeserializer listed")
    eq("struct", found.kind)
    eq("https://docs.rs/serde/1.0.200/serde/de/value/struct.StrDeserializer.html", found.url)
  end)

  it("parses crates.io search", function()
    local items = docsrs.parse_search(vim.json.decode(fixture("crates_search.json")))
    eq("serde", items[1].title)
    eq("https://docs.rs/serde/latest/serde/", items[1].url)
  end)
end)

describe("github", function()
