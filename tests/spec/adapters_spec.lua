describe("algolia", function()
  it("parses DocSearch hits, deduped by url", function()
    local items = require("rtfm.adapters.algolia").parse_hits(vim.json.decode(fixture("algolia_hits.json")))
    eq(2, #items)
    eq("Dynamic routes", items[1].title)
    eq("Guide › Routing", items[1].kind)
    eq("dynamic-routes", items[1].fragment)
  end)

  it("refuses to run without credentials", function()
    local err = await(function(cb)
      require("rtfm.adapters.algolia").search({ id = "x" }, "q", cb)
    end)
    contains(err, "app_id")
  end)
end)

describe("sitemap", function()
  local sm = require("rtfm.adapters.sitemap")
  it("derives titles from paths and applies filters", function()
    local items = sm.parse(fixture("sitemap.xml"), { exclude = "^/blog/" })
    eq(4, #items)
    local titles = vim.tbl_map(function(i)
      return i.title
    end, items)
    ok(vim.tbl_contains(titles, "Build and deploy"))
    ok(vim.tbl_contains(titles, "Getting started"))
    local only = sm.parse(fixture("sitemap.xml"), { include = "^/reference/" })
    eq(1, #only)
    eq("reference/cli", only[1].kind)
  end)
end)

describe("devdocs", function()
  local dd = require("rtfm.adapters.devdocs")
  it("resolves devdocs links across docs", function()
    local r = dd.resolve({ slug = "python~3.12" }, "https://devdocs.io/python~3.12/library/pickle#module-pickle")
    eq("python~3.12", r.source_id)
    eq("library/pickle", r.item.page)
    eq("module-pickle", r.item.fragment)
  end)
  it("builds sources from catalog entries", function()
    local s = dd.source_from_entry({ slug = "node~20_lts", name = "Node.js", version = "20 LTS", mtime = 1, links = {} })
    eq("Node.js 20 LTS", s.name)
    eq("node", s.base)
  end)
end)

describe("registry", function()
  local sources = require("rtfm.sources")
  it("resolves parametric ids", function()
    local err, s = await(function(cb)
      sources.get("docsrs:tokio@1.37.0", cb)
    end)
    eq(nil, err)
    eq("tokio", s.crate)
    eq("local", sources.mode(s))
    eq("remote", sources.mode(sources.get_sync("docsrs")))
  end)
  it("respects user overrides", function()
    require("rtfm.config").options.sources = { mdn = false, mine = { adapter = "sitemap", url = "https://x/sitemap.xml" } }
    local ids = vim.tbl_map(function(s)
      return s.id
    end, sources.static())
    ok(vim.tbl_contains(ids, "mine"))
    ok(not vim.tbl_contains(ids, "mdn"))
    require("rtfm.config").options.sources = {}
  end)
end)
