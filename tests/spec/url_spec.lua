local url = require("rtfm.url")

it("resolves relative paths", function()
  eq("https://devdocs.io/go/errors/index#New", url.join("https://devdocs.io/go/context/index", "../errors/index#New"))
  eq("https://devdocs.io/go/context/foo", url.join("https://devdocs.io/go/context/index", "foo"))
  eq("https://docs.rs/serde/1.0/serde/de/trait.X.html", url.join("https://docs.rs/serde/1.0/serde/", "de/trait.X.html"))
end)

it("resolves absolute, protocol-relative and fragment refs", function()
  eq("https://pkg.go.dev/sync#WaitGroup", url.join("https://pkg.go.dev/golang.org/x/sync/errgroup", "/sync#WaitGroup"))
  eq("https://cdn.example.com/x", url.join("https://a.com/b/c", "//cdn.example.com/x"))
  eq("https://a.com/b/c#frag", url.join("https://a.com/b/c", "#frag"))
  eq("https://a.com/b/c?q=1", url.join("https://a.com/b/c?x", "?q=1"))
  eq("http://other.org/p", url.join("https://a.com/b", "http://other.org/p"))
end)

it("handles dot segments", function()
  eq("https://a.com/x/", url.join("https://a.com/x/y/z", "../"))
  eq("https://a.com/", url.join("https://a.com/x", "../../.."))
end)

it("parses and formats", function()
  local p = url.parse("https://h.com/p/a?q=1#f")
  eq("https", p.scheme)
  eq("h.com", p.host)
  eq("/p/a", p.path)
  eq("q=1", p.query)
  eq("f", p.fragment)
  eq("https://h.com/p/a?q=1#f", url.format(p))
end)

it("encodes and decodes", function()
  eq("a%20b%2Fc", url.encode("a b/c"))
  eq("a b/c", url.decode("a%20b%2Fc"))
end)
